-- ==========================================
-- HYER DATABASE RESET SCRIPT (FIXED - CASCADE)
-- ==========================================
-- Hata Düzeltmesi: 'cannot drop table jobs because other objects depend on it'
-- Çözüm: CASCADE ifadesi ekleyerek bağımlı tabloları (applications vb.) da siliyoruz.

-- 1. TEMİZLİK (DROP EVERYTHNG WITH CASCADE)
-- DİKKAT: jobs ve profiles tablolarına bağlı her şeyi (applications vb.) siler!

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
DROP FUNCTION IF EXISTS public.handle_new_user();

-- View'lar
DROP VIEW IF EXISTS public.available_jobs CASCADE;

-- Tablolar (Sıralama önemli ama CASCADE kullanınca esniyor)
DROP TABLE IF EXISTS public.applications CASCADE; -- Varsa başvurular tablosu
DROP TABLE IF EXISTS public.jobs CASCADE;
DROP TABLE IF EXISTS public.profiles CASCADE;

-- Tipler
DROP TYPE IF EXISTS public.job_status CASCADE;
DROP TYPE IF EXISTS public.user_role CASCADE;

-- 2. UZANTILAR (EXTENSIONS)
CREATE EXTENSION IF NOT EXISTS postgis SCHEMA extensions;

-- 3. ENUMLAR (TİPLER)
CREATE TYPE public.user_role AS ENUM ('business', 'tasker');
CREATE TYPE public.job_status AS ENUM ('open', 'filled', 'completed', 'cancelled');

-- 4. TABLOLAR

-- PROFILES TABLE
CREATE TABLE public.profiles (
  id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
  role public.user_role NOT NULL DEFAULT 'tasker',
  full_name TEXT,
  avatar_url TEXT,
  bio TEXT,           -- Yeni: Biyografi
  phone_number TEXT,  -- Yeni: Telefon
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- JOBS TABLE
CREATE TABLE public.jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE NOT NULL,
  title TEXT NOT NULL,
  description TEXT,
  hourly_rate NUMERIC,
  job_type TEXT NOT NULL DEFAULT 'paid', -- 'paid' veya 'volunteer'
  -- Coğrafi konum
  location GEOGRAPHY(POINT, 4326), 
  address_text TEXT,
  start_time TIMESTAMPTZ NOT NULL,
  end_time TIMESTAMPTZ NOT NULL,
  status public.job_status DEFAULT 'open' NOT NULL,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Index
CREATE INDEX jobs_geo_index ON public.jobs USING GIST (location);

-- APPLICATIONS TABLE
CREATE TABLE public.applications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id BIGINT REFERENCES public.jobs(id) ON DELETE CASCADE NOT NULL,
  tasker_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  proof_url TEXT,
  completed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  UNIQUE(job_id, tasker_id)
);

-- RLS FOR APPLICATIONS
ALTER TABLE public.applications ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Taskers can view own applications"
ON public.applications FOR SELECT
USING (auth.uid() = tasker_id);

CREATE POLICY "Business can view applications for their jobs"
ON public.applications FOR SELECT
USING (EXISTS (
  SELECT 1 FROM public.jobs
  WHERE jobs.id = applications.job_id
  AND jobs.business_id = auth.uid()
));

CREATE POLICY "Taskers can apply"
ON public.applications FOR INSERT
WITH CHECK (auth.uid() = tasker_id);


CREATE POLICY "Business can update status for their jobs"
ON public.applications FOR UPDATE
USING (EXISTS (
  SELECT 1 FROM public.jobs
  WHERE jobs.id = applications.job_id
  AND jobs.business_id = auth.uid()
));

CREATE POLICY "Taskers can update own applications"
ON public.applications FOR UPDATE
USING (auth.uid() = tasker_id);

-- 5. VIEWS (GÖRÜNÜMLER)

-- AVAILABLE JOBS VIEW
CREATE OR REPLACE VIEW public.available_jobs AS
SELECT
  j.id,
  j.business_id,
  j.title,
  j.description,
  j.hourly_rate,
  j.job_type,
  j.address_text,
  j.start_time,
  j.end_time,
  j.status,
  j.created_at,
  -- PostGIS kolonundan enlem ve boylamı ayıkla
  st_y(j.location::geometry) as lat,
  st_x(j.location::geometry) as lng,
  -- Profil bilgileri
  p.full_name as business_name,
  p.avatar_url as business_avatar
FROM public.jobs j
JOIN public.profiles p ON j.business_id = p.id;

-- 6. RLS (GÜVENLİK POLİTİKALARI)

-- PROFILES RLS
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public profiles are viewable by everyone"
ON public.profiles FOR SELECT USING (true);

CREATE POLICY "Users can insert their own profile"
ON public.profiles FOR INSERT WITH CHECK (auth.uid() = id);

CREATE POLICY "Users can update own profile"
ON public.profiles FOR UPDATE USING (auth.uid() = id);

-- JOBS RLS
ALTER TABLE public.jobs ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Jobs are viewable by everyone"
ON public.jobs FOR SELECT USING (true);

CREATE POLICY "Authenticated users (Business) can insert jobs"
ON public.jobs FOR INSERT 
TO authenticated 
WITH CHECK (true);

CREATE POLICY "Users can update own jobs"
ON public.jobs FOR UPDATE
USING (auth.uid() = business_id);

CREATE POLICY "Users can delete own jobs"
ON public.jobs FOR DELETE
USING (auth.uid() = business_id);


-- 7. OTOMATİK PROFİL OLUŞTURMA (TRIGGER)

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, role, full_name, created_at)
  VALUES (
    new.id,
    -- Metadata'dan rolü al, yoksa 'tasker' yap.
    (COALESCE(new.raw_user_meta_data->>'role', 'tasker'))::public.user_role,
    COALESCE(new.raw_user_meta_data->>'full_name', new.email),
    new.created_at
  );
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();
